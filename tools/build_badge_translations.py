"""Build translated Achievements / Settings strings and badge texts.

Source:  tools/badge_i18n/<lang>.txt, one "key|text" per line ("#" = comment).
  str.<name>            -> <string name> in res/values-<lang>/strings_badges.xml
  plural.<name>.<qty>   -> <plurals name><item quantity=qty>
  cat.<id>.title|subtitle, badge.<id>.title|description|hint
                        -> assets/badges/badges-<tag>.json (same shape as badges.json, text only)
Usage: python3 tools/build_badge_translations.py [lang ...]   (default: every file in tools/badge_i18n)
       python3 tools/build_badge_translations.py --template  (prints the English source keys)
"""
import json
import os
import re
import sys
from xml.sax.saxutils import escape

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MAIN = os.path.join(ROOT, "app/src/main")
I18N = os.path.join(ROOT, "tools/badge_i18n")
BASE_STRINGS = ["badge_screen_title", "badge_screen_subtitle", "badge_summary", "badge_locked", "badge_earned",
                "badge_earned_on", "badge_remaining", "badge_empty", "badge_next_up", "badge_view_all",
                "badge_unlocked_celebration_title", "badge_unlocked_celebration_more", "badge_continue",
                "badge_share", "badge_share_chooser", "badge_share_message", "badge_tier_bronze",
                "badge_tier_silver", "badge_tier_gold", "badge_tier_jade",
                "pref_category_general", "pref_tts_engine", "pref_version"]
PLURALS = ["badge_unit_session", "badge_unit_day", "badge_unit_minute", "badge_unit_kcal",
           "badge_unit_program", "badge_unit_week", "badge_unit_month"]
QUANTITIES = ("zero", "one", "two", "few", "many", "other")
# values folder -> badge json tags (Locale.getLanguage() may give either code)
TAGS = {"in": ["in", "id"], "no": ["no", "nb"], "zh-rCN": ["zh-cn", "zh"], "zh-rTW": ["zh-tw"]}


def catalog():
    return json.load(open(os.path.join(MAIN, "assets/badges/badges.json"), encoding="utf-8"))


def template():
    s = open(os.path.join(MAIN, "res/values/strings.xml"), encoding="utf-8").read()
    for name in BASE_STRINGS:
        m = re.search(r'<string name="%s">(.*?)</string>' % name, s)
        print("str.%s|%s" % (name, m.group(1) if m else ""))
    for name in PLURALS:
        for q, text in re.findall(r'<item quantity="(\w+)">(.*?)</item>',
                                  re.search(r'<plurals name="%s">(.*?)</plurals>' % name, s, re.S).group(1)):
            print("plural.%s.%s|%s" % (name, q, text))
    c = catalog()
    for cat in c["categories"]:
        print("cat.%s.title|%s" % (cat["id"], cat["title"]))
        print("cat.%s.subtitle|%s" % (cat["id"], cat["subtitle"]))
    for b in c["badges"]:
        for f in ("title", "description", "hint"):
            print("badge.%s.%s|%s" % (b["id"], f, b[f]))


def xml_text(text):
    text = escape(text)
    # Android string escaping: apostrophes and leading @/? need a backslash; quotes already escaped in source.
    text = re.sub(r"(?<!\\)'", r"\\'", text)
    return text


def build(lang):
    entries = {}
    for line in open(os.path.join(I18N, lang + ".txt"), encoding="utf-8"):
        line = line.rstrip("\n")
        if not line.strip() or line.startswith("#"):
            continue
        key, text = line.split("|", 1)
        entries[key] = text.strip()
    c = catalog()
    missing = [n for n in BASE_STRINGS if "str." + n not in entries]
    missing += ["plural.%s.other" % n for n in PLURALS if "plural.%s.other" % n not in entries]
    for cat in c["categories"]:
        missing += [k for k in ("cat.%s.title" % cat["id"], "cat.%s.subtitle" % cat["id"]) if k not in entries]
    for b in c["badges"]:
        missing += ["badge.%s.%s" % (b["id"], f) for f in ("title", "description", "hint")
                    if "badge.%s.%s" % (b["id"], f) not in entries]
    assert not missing, (lang, missing)
    for name in BASE_STRINGS:
        assert entries["str." + name].count("%") == len(re.findall(r"%\d\$[sd]", entries["str." + name])), (lang, name)

    lines = ['<?xml version="1.0" encoding="utf-8"?>',
             "<!-- Generated by tools/build_badge_translations.py from tools/badge_i18n/%s.txt -->" % lang,
             "<resources>"]
    for name in BASE_STRINGS:
        lines.append('    <string name="%s">%s</string>' % (name, xml_text(entries["str." + name])))
    for name in PLURALS:
        lines.append('    <plurals name="%s">' % name)
        for q in QUANTITIES:
            key = "plural.%s.%s" % (name, q)
            if key in entries:
                lines.append('        <item quantity="%s">%s</item>' % (q, xml_text(entries[key])))
        lines.append("    </plurals>")
    lines.append("</resources>")
    out_dir = os.path.join(MAIN, "res/values-" + lang)
    open(os.path.join(out_dir, "strings_badges.xml"), "w", encoding="utf-8").write("\n".join(lines) + "\n")

    data = {
        "categories": [{"id": cat["id"], "title": entries["cat.%s.title" % cat["id"]],
                        "subtitle": entries["cat.%s.subtitle" % cat["id"]]} for cat in c["categories"]],
        "badges": [{"id": b["id"], "title": entries["badge.%s.title" % b["id"]],
                    "description": entries["badge.%s.description" % b["id"]],
                    "hint": entries["badge.%s.hint" % b["id"]]} for b in c["badges"]],
    }
    for tag in TAGS.get(lang, [lang]):
        with open(os.path.join(MAIN, "assets/badges/badges-%s.json" % tag), "w", encoding="utf-8") as f:
            json.dump(data, f, ensure_ascii=False, indent=1)
    print(lang, "ok")


if __name__ == "__main__":
    if sys.argv[1:] == ["--template"]:
        template()
    else:
        langs = sys.argv[1:] or sorted(f[:-4] for f in os.listdir(I18N) if f.endswith(".txt"))
        for lang in langs:
            build(lang)
